-- RAW landing tables, loaded by the mail-room / workshop / telemetry ingestion jobs
-- Owner: platform team. Do not change column order: ingestion is positional (CSV).

CREATE OR REPLACE TABLE RAW.RAW_LETTERS (
    LETTER_ID       VARCHAR,
    RECEIVED_AT     TIMESTAMP_NTZ,
    CHANNEL         VARCHAR,
    POSTAL_COUNTRY  VARCHAR,
    RAW_PAYLOAD     VARCHAR
);

CREATE OR REPLACE TABLE RAW.RAW_BEHAVIOUR_EVENTS (
    EVENT_ID       VARCHAR,
    CHILD_ID       VARCHAR,
    EVENT_TS       TIMESTAMP_NTZ,
    EVENT_TYPE     VARCHAR,
    SCORE_DELTA    NUMBER(38,0),
    REPORTED_BY    VARCHAR,
    SOURCE_SYSTEM  VARCHAR
);

CREATE OR REPLACE TABLE RAW.RAW_ELF_SHIFTS (
    SHIFT_ID        VARCHAR,
    ELF_ID          VARCHAR,
    SHIFT_DATE      DATE,
    WORKSHOP_ID     VARCHAR,
    STATUS          VARCHAR,
    HOURS_WORKED    NUMBER(5,1),
    TOYS_BUILT      NUMBER(38,0),
    TOYS_DEFECTIVE  NUMBER(38,0)
);

CREATE OR REPLACE TABLE RAW.RAW_SLEIGH_SHIPMENTS (
    SHIPMENT_ID            VARCHAR,
    SHIPMENT_DATE          DATE,
    ORIGIN_WORKSHOP_ID     VARCHAR,
    DESTINATION_REGION_ID  VARCHAR,
    REINDEER_TEAM_ID       VARCHAR,
    LEAD_REINDEER_ID       VARCHAR,
    PLANNED_GIFTS          NUMBER(38,0),
    DELIVERED_GIFTS        NUMBER(38,0),
    DEPARTED_AT            TIMESTAMP_NTZ,
    ARRIVED_AT             TIMESTAMP_NTZ,
    DELAY_MINUTES          NUMBER(8,1),
    STATUS                 VARCHAR
);

CREATE OR REPLACE TABLE RAW.RAW_WEATHER_READINGS (
    READING_ID      VARCHAR,
    REGION_ID       VARCHAR,
    READING_TS      TIMESTAMP_NTZ,
    TEMPERATURE_C   NUMBER(6,1),
    SNOWFALL_CM     NUMBER(6,1),
    WIND_SPEED_KPH  NUMBER(6,1),
    VISIBILITY_KM   NUMBER(6,2),
    SENSOR_ID       VARCHAR
);

CREATE OR REPLACE TABLE RAW.RAW_REINDEER_HEALTH (
    REINDEER_ID    VARCHAR,
    CHECK_DATE     DATE,
    HEALTH_STATUS  VARCHAR,
    BODY_TEMP_C    NUMBER(4,1),
    CARROTS_EATEN  NUMBER(5,1),
    VET_NOTE       VARCHAR
);

CREATE OR REPLACE TABLE RAW.RAW_INCIDENTS (
    INCIDENT_ID  VARCHAR,
    REPORTED_AT  TIMESTAMP_NTZ,
    REGION_ID    VARCHAR,
    WORKSHOP_ID  VARCHAR,
    CATEGORY     VARCHAR,
    SEVERITY     NUMBER(38,0),
    DESCRIPTION  VARCHAR,
    STATUS       VARCHAR
);
